// Assemble one self-contained SQL Editor transaction from reviewed sources.
import {readFile,writeFile,mkdir} from 'node:fs/promises'
const root=new URL('../',import.meta.url)
const read=async name=>(await readFile(new URL(`supabase/migrations/${name}.sql`,root),'utf8')).replace(/\r\n/g,'\n')
const extract=(sql,name)=>sql.slice(sql.indexOf(`create or replace function public.${name}(`),sql.indexOf('$$;',sql.indexOf(`create or replace function public.${name}(`))+3)
function resilient(sql){
  sql=sql.replace('tariff_verified_email)','tariff_verified_email,confirmation_job_state,tariff_review_required)')
    .replace("chosen_source='verified_member' then verified else null end)","chosen_source='verified_member' then verified else null end,'pending',needs_review)")
  // Legacy RPC retains its existing price/code decision while gaining durable intent.
  sql=sql.replace('payment_method,registration_status)','payment_method,registration_status,confirmation_job_state,tariff_review_required)')
    .replace('input.payment_method,input.registration_status)','input.payment_method,input.registration_status,\'pending\',false)')
  const start=sql.indexOf('  -- Idempotent even')
  const end=sql.indexOf("  return jsonb_build_object('id'",start)
  if(start<0||end<0)throw new Error('Unexpected registration source')
  sql=sql.slice(0,start)+`  perform public.ensure_registration_job(p.id);
  select * into p from public.participants x where x.id=p.id;
`+sql.slice(end)
  sql=sql.replace("'payment_amount',p.payment_amount)","'payment_amount',p.payment_amount,'confirmation_job_state',p.confirmation_job_state,'tariff_review_required',coalesce(p.tariff_review_required,false))")
  if(sql.includes('chosen_source')){
    sql=sql.replace('verified text;','verified text; needs_review boolean:=false;')
      .replace("  verified := lower(trim(registration->>'verified_email'));","  verified := lower(trim(registration->>'verified_email'));\n  needs_review := coalesce((registration->>'tariff_review_required')::boolean,false);")
      .replace("input.is_member := true; chosen_source := 'code';","input.is_member := true; chosen_source := 'code'; needs_review := false;")
      .replace("    select m.id into eligible from public.club_members m where m.club_id=input.club_id and m.email=verified and m.is_active for share;\n    if eligible is not null then input.is_member := true; chosen_source := 'verified_member'; end if;",`    begin
      select m.id into eligible from public.club_members m where m.club_id=input.club_id and m.email=verified and m.is_active for share;
      if eligible is not null then input.is_member := true; chosen_source := 'verified_member'; needs_review := false; end if;
    exception when others then needs_review := true;
    end;`)
  }
  return sql
}
const five=await read('20261105_registration_confirmation_outbox'),six=await read('20261106_verified_member_tariffs')
let hardening=await read('20261108_resilient_registration')
const marker='-- REGISTRATION_FUNCTIONS: generated by scripts/build-registration-repair.mjs.'
// Marker region is delimited so repeated generation is deterministic.
const markerEnd='-- END_REGISTRATION_FUNCTIONS'
const markerStart=hardening.indexOf(marker),oldEnd=hardening.indexOf(markerEnd,markerStart)
if(markerStart<0)throw new Error('Missing function marker')
const functions=[resilient(extract(five,'register_with_confirmation')),resilient(extract(six,'register_with_tariff_confirmation'))].join('\n\n')+`
revoke all on function public.register_with_confirmation(jsonb),public.register_with_tariff_confirmation(jsonb) from public,anon,authenticated;
grant execute on function public.register_with_confirmation(jsonb),public.register_with_tariff_confirmation(jsonb) to service_role;
`
hardening=hardening.slice(0,markerStart)+marker+'\n'+functions+markerEnd+hardening.slice(oldEnd<0?markerStart+marker.length:oldEnd+markerEnd.length)
await writeFile(new URL('supabase/migrations/20261108_resilient_registration.sql',root),hardening)
